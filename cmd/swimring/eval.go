package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"time"

	"github.com/SlateGitOrg/swimring/experiment"
	"github.com/SlateGitOrg/swimring/swim"
)

// evalPlan holds the experiment grid; quick shrinks it for smoke runs.
type evalPlan struct {
	detSizes    []int
	detLosses   []float64
	detTrials   int
	detOffSizes []int
	fpSizes     []int
	fpLosses    []float64
	fpPeriods   int
	lgLags      []time.Duration
	lgPeriods   int
	lgRuns      int
	balNodes    []int
	balVNodes   []int
	balSets     int
	balKeys     int
}

func plan(quick bool) evalPlan {
	if quick {
		return evalPlan{
			detSizes: []int{8, 32}, detLosses: []float64{0, 0.1}, detTrials: 8, detOffSizes: []int{8},
			fpSizes: []int{16}, fpLosses: []float64{0.1, 0.2}, fpPeriods: 200,
			lgLags: []time.Duration{2 * time.Second}, lgPeriods: 100, lgRuns: 1,
			balNodes: []int{10}, balVNodes: []int{1, 64}, balSets: 3, balKeys: 5000,
		}
	}
	return evalPlan{
		detSizes: []int{8, 16, 32, 64, 128}, detLosses: []float64{0, 0.05, 0.1}, detTrials: 40,
		detOffSizes: []int{8, 32, 128},
		fpSizes:     []int{16, 64, 128}, fpLosses: []float64{0.05, 0.1, 0.2, 0.3}, fpPeriods: 1000,
		lgLags: []time.Duration{1200 * time.Millisecond, 2 * time.Second, 4 * time.Second}, lgPeriods: 300, lgRuns: 3,
		balNodes: []int{10, 100}, balVNodes: []int{1, 16, 64, 256}, balSets: 10, balKeys: 50000,
	}
}

func runEval(args []string, stdout, stderr io.Writer) error {
	fs := flag.NewFlagSet("eval", flag.ContinueOnError)
	fs.SetOutput(stderr)
	quick := fs.Bool("quick", false, "small grid for smoke testing")
	out := fs.String("out", "", "also write the report to this file")
	seed := fs.Uint64("seed", 2002, "base seed")
	if err := fs.Parse(args); err != nil {
		return errUsage
	}
	p := plan(*quick)
	var buf bytes.Buffer
	w := io.MultiWriter(&buf, stdout)
	start := time.Now()
	cmd := "go run ./cmd/swimring eval"
	if *quick {
		cmd += " -quick"
	}
	fmt.Fprintf(w, "# swimring evaluation\n\nGenerated by `%s -seed %d`. Every number below comes from a seeded, deterministic\nsimulation (package `sim`); re-running the command reproduces it exactly.\nDefaults: T = 1 s probe period, 500 ms probe timeout, k = 3 relays, λ = 4, α = 4, β = 6,\none-way latency 1–4 ms. Latencies are in protocol periods T.\n", cmd, *seed)

	section := func(title, text string) { fmt.Fprintf(w, "\n## %s\n\n%s\n\n", title, text) }

	section("1. Failure detection vs cluster size and loss (Lifeguard on)",
		fmt.Sprintf("One random member crashes per trial (%d trials per cell) at a random phase of the period. "+
			"*First ping* is the period in which some survivor first pings the crashed member; the SWIM paper "+
			"predicts E = 1/(1-(1-1/(n-1))^(n-1)) for random target choice (→ e/(e-1) ≈ 1.582); this implementation "+
			"uses shuffled round-robin, whose expectation is given alongside. *Dissemination* is the time from the first "+
			"death declaration until every survivor has it.", p.detTrials))
	det, err := experiment.RunDetection(experiment.DetectionSpec{Sizes: p.detSizes, Losses: p.detLosses, Trials: p.detTrials, Seed: *seed, Lifeguard: swim.LifeguardAll()})
	if err != nil {
		return err
	}
	if err := experiment.WriteDetectionTable(w, det); err != nil {
		return err
	}

	section("2. Failure detection with Lifeguard off (plain SWIM + suspicion)",
		"Same experiment, loss 0. Without dynamic suspicion every member uses the fixed minimum suspicion timeout α·log10(n)·T, "+
			"so declarations come sooner; Lifeguard starts at β times that and needs independent confirmations to shrink it.")
	detOff, err := experiment.RunDetection(experiment.DetectionSpec{Sizes: p.detOffSizes, Losses: []float64{0}, Trials: p.detTrials, Seed: *seed + 1, Lifeguard: swim.LifeguardOff()})
	if err != nil {
		return err
	}
	if err := experiment.WriteDetectionTable(w, detOff); err != nil {
		return err
	}

	for i, v := range []experiment.Variant{
		{Name: "Lifeguard on", Lifeguard: swim.LifeguardAll()},
		{Name: "Lifeguard off", Lifeguard: swim.LifeguardOff()},
	} {
		section(fmt.Sprintf("3%c. False positives under message loss (%s)", 'a'+i, v.Name),
			fmt.Sprintf("Healthy clusters, independent loss on every packet, %d protocol periods each. The model column is the "+
				"paper's loss analysis: a probe of a live member fails only if the direct ping/ack loses a message **and** all k "+
				"four-message indirect paths do, P = (1-(1-p)²)(1-(1-p)⁴)^k. (meas−model)/SE is the z-score of the measurement.",
				p.fpPeriods))
		fp, err := experiment.RunFalsePositives(experiment.FalsePositiveSpec{Sizes: p.fpSizes, Losses: p.fpLosses, Periods: p.fpPeriods, Seed: *seed + 2, Lifeguard: v.Lifeguard})
		if err != nil {
			return err
		}
		if err := experiment.WriteFalsePositiveTable(w, fp); err != nil {
			return err
		}
	}

	for i, lag := range p.lgLags {
		section(fmt.Sprintf("4%c. Lifeguard ablation: 2 slow members, inbound lag %v (n=32)", 'a'+i, lag),
			fmt.Sprintf("Two members process every inbound packet %v late while their timers stay on time (a starved receive path). "+
				"%d runs × %d periods per variant. *Accusations* are suspicions a member raised from its own failed probe.",
				lag, p.lgRuns, p.lgPeriods))
		lg, err := experiment.RunLifeguard(experiment.LifeguardSpec{Size: 32, Slow: 2, Lag: lag, Periods: p.lgPeriods, Runs: p.lgRuns, Seed: *seed + 3, Variants: experiment.StandardVariants()})
		if err != nil {
			return err
		}
		if err := experiment.WriteLifeguardTable(w, lg); err != nil {
			return err
		}
	}

	section("5. Ring balance and key movement",
		fmt.Sprintf("Share of the hash circle per node, pooled over %d random node-name sets; key movement measured with %d random keys "+
			"when one node joins.", p.balSets, p.balKeys))
	bal, err := experiment.RunBalance(experiment.BalanceSpec{Nodes: p.balNodes, VNodes: p.balVNodes, Sets: p.balSets, Keys: p.balKeys, Seed: *seed})
	if err != nil {
		return err
	}
	if err := experiment.WriteBalanceTable(w, bal); err != nil {
		return err
	}
	fmt.Fprintf(stderr, "eval finished in %v\n", time.Since(start).Round(time.Millisecond))
	if *out != "" {
		if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
			return fmt.Errorf("create %s: %w", filepath.Dir(*out), err)
		}
		if err := os.WriteFile(*out, buf.Bytes(), 0o644); err != nil {
			return fmt.Errorf("write %s: %w", *out, err)
		}
	}
	return nil
}
